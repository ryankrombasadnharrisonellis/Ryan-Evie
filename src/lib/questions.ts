/** Both of us get the same question each day — "today" is the UK calendar day. */
export const QUESTION_TZ = "Europe/London";

export function todayQDate(now = new Date()) {
  return localDateStr(now, QUESTION_TZ);
}

const LEGACY_COUNT = 108; // size of the original list
const EXPANDED_FROM = "2026-10-13"; // first day of the year-long rotation

function dayNumber(qdate: string) {
  const [y, m, d] = qdate.split("-").map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000);
}

export function questionIndexFor(qdate: string) {
  // Days before the expansion keep their original question, so nothing already answered changes.
  if (qdate < EXPANDED_FROM) return dayNumber(qdate) % LEGACY_COUNT;
  // From then on: start with the brand-new questions, then cycle through all of them (no repeats for a year).
  const offset = dayNumber(qdate) - dayNumber(EXPANDED_FROM);
  return (LEGACY_COUNT + offset) % QUESTIONS.length;
}

